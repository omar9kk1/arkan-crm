-- Manual (not modeled by Prisma): enforce ONLY ONE PENDING edit revision per property.
-- A regular UNIQUE("propertyId") is deliberately NOT used so that historical
-- APPROVED/REJECTED revisions remain allowed. Application validation is still required,
-- but this database-level partial unique index is the authoritative guarantee.
-- PostgreSQL 12+ supports partial unique indexes; this project targets PostgreSQL 16.
CREATE UNIQUE INDEX "PropertyRevision_one_pending_per_property"
  ON "PropertyRevision" ("propertyId")
  WHERE "status" = 'PENDING';

-- Manual (not modeled by Prisma): RequestedProperty budget range rules.
-- Both values optional; min-only, max-only and both-empty are all allowed.
-- Negative amounts are invalid and min must not exceed max when both are present.
-- Application-level validation is still required; this CHECK is a database safety net.
ALTER TABLE "RequestedProperty" ADD CONSTRAINT "RequestedProperty_budget_range_check"
  CHECK (
    ("budgetMin" IS NULL OR "budgetMin" >= 0)
    AND ("budgetMax" IS NULL OR "budgetMax" >= 0)
    AND ("budgetMin" IS NULL OR "budgetMax" IS NULL OR "budgetMin" <= "budgetMax")
  );
